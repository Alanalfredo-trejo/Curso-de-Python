#numero entero -> integer : int
numero = 123
print(numero)
print(type(numero))

# numero decimal -> float : float
decimal = 12.4
print(decimal)
print(type(decimal))

#texto -> String : str
texto = "lo que sea"
print(type(texto))

# nulo -> None : None 
nulo = None
print(nulo)
print(type(nulo))

# booleano -> Boolean : bool
mayoria_de_edad = False
print(type(mayoria_de_edad))


